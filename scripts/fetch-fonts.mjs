// Fetches koji's web fonts from Google at build time so the site serves them
// itself (src/app/fonts/, gitignored). Runs as `prebuild` and `predev`.
//
// Why not next/font: it asks Google for every weight x style combination, so
// Fraunces would gain an italic 400 we have never loaded. Today italic serif
// text at weight 400 (stay notes, dinner names) falls back to the italic 300
// face; with a real 400 it would come out heavier. This script keeps Google's
// own CSS for the exact request the old <link> made (same faces, same
// unicode-range subsets, same font-display), only pointing it at local files.
// layout.tsx imports the CSS, so Next emits the files under /_next/static/media
// (immutable, and cache-first in the service worker, so fonts work offline).
//
// Keep FAMILIES in step with what the CSS uses. A failed fetch fails the build:
// Vercel keeps the previous deploy live, which beats shipping without fonts.
import { mkdir, writeFile, readdir, rm, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const FAMILIES =
  'family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300' +
  '&family=Geist+Mono:wght@400;500;700' +
  '&family=Manrope:wght@300;400;500;600' +
  '&display=swap';
const CSS_URL = `https://fonts.googleapis.com/css2?${FAMILIES}`;
// Google varies the CSS by browser; a current Safari and Chrome get the same
// woff2 + unicode-range CSS, which is what koji's readers were served.
const UA = 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'app', 'fonts');
const cssPath = join(dir, 'google.css');

async function get(url, as) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return as === 'text' ? await res.text() : Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (attempt >= 3) throw err;
      await new Promise((r) => setTimeout(r, 1000 * attempt));
    }
  }
}

async function main() {
  // Dev restarts reuse a fresh copy; builds (and FONTS_REFRESH=1) always fetch.
  if (process.env.npm_lifecycle_event === 'predev' && !process.env.FONTS_REFRESH) {
    try {
      const s = await stat(cssPath);
      if (Date.now() - s.mtimeMs < 7 * 864e5) return;
    } catch {}
  }
  const css = await get(CSS_URL, 'text');
  const urls = [...new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)'"\s]+\.woff2/g) || [])];
  if (urls.length === 0) throw new Error('no woff2 files in the Google Fonts CSS');

  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  const names = new Map();
  await Promise.all(urls.map(async (u) => {
    // Google's file names are content hashes; keep the family folder in front
    // so two families can't collide.
    const parts = new URL(u).pathname.split('/');
    const name = `${parts[2]}-${parts[parts.length - 1]}`;
    names.set(u, name);
    await writeFile(join(dir, name), await get(u, 'buffer'));
  }));

  let local = css;
  for (const [u, name] of names) local = local.split(u).join(`./${name}`);
  await writeFile(cssPath,
    `/* Generated by scripts/fetch-fonts.mjs from\n   ${CSS_URL}\n   Do not edit; do not commit. */\n${local}`);
  const files = (await readdir(dir)).filter((f) => f.endsWith('.woff2'));
  console.log(`fonts: ${files.length} files, ${(css.match(/@font-face/g) || []).length} faces -> src/app/fonts`);
}

main().catch((err) => {
  console.error(`fonts: could not fetch Google Fonts (${err.message}).`);
  process.exit(1);
});
